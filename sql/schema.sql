CREATE TABLE IF NOT EXISTS public.sellers (
    seller_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_name TEXT NOT NULL,
    region TEXT NOT NULL,
    created_at DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.buyers (
    buyer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_name TEXT NOT NULL,
    region TEXT NOT NULL,
    created_at DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES public.sellers(seller_id),
    make TEXT NOT NULL,
    model TEXT NOT NULL,
    model_year INTEGER NOT NULL CHECK (model_year BETWEEN 1980 AND 2030),
    mileage INTEGER NOT NULL CHECK (mileage >= 0),
    price NUMERIC(10,2) NOT NULL CHECK (price > 0),
    listing_status TEXT NOT NULL DEFAULT 'active'
        CHECK (listing_status IN ('active','pending','sold')),
    posted_at DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.offers (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(vehicle_id),
    buyer_id BIGINT NOT NULL REFERENCES public.buyers(buyer_id),
    offer_amount NUMERIC(10,2) NOT NULL CHECK (offer_amount > 0),
    offer_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (offer_status IN ('pending','accepted','rejected')),
    created_at DATE NOT NULL
);
